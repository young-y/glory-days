package com.glory.app.domain;

import com.glory.foundation.basic.crypto.CryptoType;
import com.glory.foundation.basic.desensitize.Desensitize;

import java.time.LocalDateTime;

/**
 * @author YY
 * @date 2026/9/27
 * @description: TODO
 */
public class DesensitizeObject {
    private String name;
    private String sex;
    private LocalDateTime birthday;
    @Desensitize(algorithm = CryptoType.AES,withPrefix = true)
    private String email;
    private String mobile;

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getSex() {
        return sex;
    }

    public void setSex(String sex) {
        this.sex = sex;
    }

    public LocalDateTime getBirthday() {
        return birthday;
    }

    public void setBirthday(LocalDateTime birthday) {
        this.birthday = birthday;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getMobile() {
        return mobile;
    }

    public void setMobile(String mobile) {
        this.mobile = mobile;
    }
}
